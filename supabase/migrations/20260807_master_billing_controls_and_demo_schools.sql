create or replace function public.set_dailybloom_demo_school(
  target_school_id bigint,
  demo_reason text,
  actor_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  target_school public.schools%rowtype;
begin
  if char_length(trim(coalesce(demo_reason, ''))) < 3 then
    raise exception 'A demo-school reason of at least 3 characters is required.';
  end if;

  select *
    into target_school
    from public.schools
   where id = target_school_id
   for update;

  if target_school.id is null then
    raise exception 'School % was not found.', target_school_id;
  end if;

  update public.schools
     set is_demo_school = true,
         demo_school_reason = trim(demo_reason),
         demo_school_set_at = now(),
         demo_school_set_by = actor_id,
         updated_at = now()
   where id = target_school_id;

  update public.school_subscriptions
     set next_billing_date = null,
         updated_at = now()
   where school_id = target_school_id;

  return jsonb_build_object(
    'school_id', target_school_id,
    'is_demo_school', true,
    'message', 'DailyBloom billing is paused for this Demo school.'
  );
end;
$$;

revoke all on function public.set_dailybloom_demo_school(bigint, text, uuid)
  from public, anon, authenticated;
grant execute on function public.set_dailybloom_demo_school(bigint, text, uuid)
  to service_role;

create or replace function public.post_school_billing_journal(
  target_school_id bigint,
  target_subscription_id bigint,
  journal_type text,
  journal_amount numeric,
  effective_on date,
  journal_reason text,
  actor_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  target_school public.schools%rowtype;
  target_subscription public.school_subscriptions%rowtype;
  new_invoice_id uuid;
  new_payment_id bigint;
  new_journal_id bigint;
  record_key text;
  reconciliation jsonb;
begin
  if journal_type not in ('credit', 'debit') then
    raise exception 'Journal type must be credit or debit.';
  end if;
  if coalesce(journal_amount, 0) <= 0 then
    raise exception 'Journal amount must be greater than zero.';
  end if;
  if effective_on is null or effective_on > current_date then
    raise exception 'Journal effective date cannot be in the future.';
  end if;
  if char_length(trim(coalesce(journal_reason, ''))) < 3 then
    raise exception 'A journal reason of at least 3 characters is required.';
  end if;

  select *
    into target_school
    from public.schools
   where id = target_school_id
   for update;
  if target_school.id is null then
    raise exception 'School % was not found.', target_school_id;
  end if;
  if target_school.is_demo_school then
    raise exception 'Demo schools do not have DailyBloom billing journals.';
  end if;

  select *
    into target_subscription
    from public.school_subscriptions
   where id = target_subscription_id
     and school_id = target_school_id
   for update;
  if target_subscription.id is null then
    raise exception 'Subscription was not found for this school.';
  end if;

  reconciliation := public.reconcile_school_billing_account(target_school_id, 599);
  record_key := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));

  if journal_type = 'credit' then
    insert into public.subscription_payments (
      school_id,
      subscription_id,
      amount,
      original_amount,
      unapplied_amount,
      payment_date,
      charge_type,
      plan_name,
      payment_method,
      notes,
      receipt_number
    )
    values (
      target_school_id,
      target_subscription.id,
      journal_amount,
      journal_amount,
      journal_amount,
      effective_on,
      'credit_journal',
      target_subscription.plan_name,
      'Journal Credit',
      'Journal credit: ' || trim(journal_reason),
      'DB-JRN-' || to_char(effective_on, 'YYYYMMDD') || '-' || record_key
    )
    returning id into new_payment_id;

    -- The normal payment trigger queues receipts. A journal is an internal
    -- adjustment, so it must not generate an automatic customer email.
    delete from public.billing_email_outbox
     where payment_id = new_payment_id
       and email_type = 'payment_receipt';

    insert into public.billing_journal_entries (
      school_id,
      payment_id,
      entry_type,
      amount,
      reason,
      created_by,
      effective_date
    )
    values (
      target_school_id,
      new_payment_id,
      'credit_journal',
      journal_amount,
      trim(journal_reason),
      actor_id,
      effective_on
    )
    returning id into new_journal_id;
  else
    insert into public.billing_invoices (
      school_id,
      subscription_id,
      invoice_number,
      external_key,
      charge_type,
      description,
      plan_name,
      issue_date,
      due_date,
      subtotal,
      vat_amount,
      total_amount,
      amount_paid,
      balance_due,
      status
    )
    values (
      target_school_id,
      target_subscription.id,
      'DB-JRN-' || to_char(effective_on, 'YYYYMMDD') || '-' || target_school_id || '-' || record_key,
      'debit-journal:' || target_school_id || ':' || gen_random_uuid()::text,
      'debit_journal',
      'Manual debit journal - ' || trim(journal_reason),
      target_subscription.plan_name,
      effective_on,
      effective_on,
      journal_amount,
      0,
      journal_amount,
      0,
      journal_amount,
      'issued'
    )
    returning id into new_invoice_id;

    insert into public.billing_journal_entries (
      school_id,
      invoice_id,
      entry_type,
      amount,
      reason,
      created_by,
      effective_date
    )
    values (
      target_school_id,
      new_invoice_id,
      'debit_journal',
      journal_amount,
      trim(journal_reason),
      actor_id,
      effective_on
    )
    returning id into new_journal_id;
  end if;

  reconciliation := public.reconcile_school_billing_account(target_school_id, 599);

  return jsonb_build_object(
    'school_id', target_school_id,
    'journal_id', new_journal_id,
    'invoice_id', new_invoice_id,
    'payment_id', new_payment_id,
    'journal_type', journal_type,
    'amount', journal_amount,
    'reconciliation', reconciliation
  );
end;
$$;

revoke all on function public.post_school_billing_journal(bigint, bigint, text, numeric, date, text, uuid)
  from public, anon, authenticated;
grant execute on function public.post_school_billing_journal(bigint, bigint, text, numeric, date, text, uuid)
  to service_role;

comment on function public.post_school_billing_journal(bigint, bigint, text, numeric, date, text, uuid) is
  'Posts a Master-only DailyBloom subscription credit or debit journal and reconciles the affected preschool account.';
