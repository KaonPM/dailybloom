-- Master billing controls for DailyBloom's own preschool subscriptions.
-- These controls deliberately do not touch learner-fee billing or parent statements.

alter table public.schools
  add column if not exists is_demo_school boolean not null default false,
  add column if not exists demo_school_reason text,
  add column if not exists demo_school_set_at timestamptz,
  add column if not exists demo_school_set_by uuid references public.profiles(id) on delete set null;

update public.schools
set is_demo_school = false
where is_demo_school is null;

comment on column public.schools.is_demo_school is
  'When true, the school remains usable but DailyBloom setup fees, recurring subscriptions, payment reminders and payment recording are disabled.';

-- Allow a debit journal to be represented by a durable invoice charge and a
-- credit journal to be represented by an auditable non-cash payment credit.
do $$
declare
  constraint_name text;
begin
  for constraint_name in
    select constraint_record.conname
    from pg_constraint constraint_record
    where constraint_record.conrelid = 'public.billing_invoices'::regclass
      and constraint_record.contype = 'c'
      and pg_get_constraintdef(constraint_record.oid) ilike '%charge_type%'
  loop
    execute format(
      'alter table public.billing_invoices drop constraint if exists %I',
      constraint_name
    );
  end loop;

  alter table public.billing_invoices
    add constraint billing_invoices_charge_type_check
    check (charge_type in ('setup_fee', 'subscription', 'debit_journal'));
end;
$$;

do $$
declare
  constraint_name text;
begin
  for constraint_name in
    select constraint_record.conname
    from pg_constraint constraint_record
    where constraint_record.conrelid = 'public.subscription_payments'::regclass
      and constraint_record.contype = 'c'
      and pg_get_constraintdef(constraint_record.oid) ilike '%charge_type%'
  loop
    execute format(
      'alter table public.subscription_payments drop constraint if exists %I',
      constraint_name
    );
  end loop;

  alter table public.subscription_payments
    add constraint subscription_payments_charge_type_check
    check (charge_type in ('setup_fee', 'subscription', 'credit_journal'));
end;
$$;

alter table public.billing_journal_entries
