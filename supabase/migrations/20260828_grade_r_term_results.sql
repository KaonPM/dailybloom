create table if not exists public.grade_r_term_results (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  classroom_id bigint not null references public.classrooms(id) on delete cascade,
  learner_id uuid not null references public.learners(id) on delete cascade,
  report_period_id bigint not null references public.report_periods(id) on delete cascade,
  subject_key text not null check (subject_key in ('english_home_language','afrikaans_first_additional_language','mathematics','life_skills')),
  term_number smallint not null check (term_number between 1 and 4),
  sba_mark numeric(5,2) check (sba_mark between 0 and 100),
  exam_mark numeric(5,2) check (exam_mark between 0 and 100),
  final_mark numeric(5,2) check (final_mark between 0 and 100),
  final_code smallint check (final_code between 1 and 4),
  confirmed_by uuid references auth.users(id) on delete set null,
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (learner_id, report_period_id, subject_key)
);

alter table public.grade_r_term_results enable row level security;

create policy "School staff read grade r term results"
on public.grade_r_term_results for select to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and (p.role = 'master' or p.school_id = grade_r_term_results.school_id)));

create policy "Principals manage grade r term results"
on public.grade_r_term_results for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and (p.role = 'master' or (p.school_id = grade_r_term_results.school_id and p.role in ('owner','principal','admin')))))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and (p.role = 'master' or (p.school_id = grade_r_term_results.school_id and p.role in ('owner','principal','admin')))));
